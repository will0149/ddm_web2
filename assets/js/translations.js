// Función para cambiar el idioma
function changeLanguage(lang) {
  // Guardar la preferencia del usuario
  localStorage.setItem('preferredLanguage', lang);

  // Actualizar todos los elementos con data-i18n
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      element.textContent = translations[lang][key];
    }
  });

  // Actualizar todos los placeholders con data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const key = element.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      element.placeholder = translations[lang][key];
    }
  });

  // Actualizar todos los elementos con data-i18n-value (para labels, etc)
  document.querySelectorAll('[data-i18n-value]').forEach(element => {
    const key = element.getAttribute('data-i18n-value');
    if (translations[lang] && translations[lang][key]) {
      element.value = translations[lang][key];
    }
  });

  // Actualizar el documento con el idioma actual
  document.documentElement.lang = lang;
}

// Obtener idioma guardado o usar el del navegador
function initializeLanguage() {
  let lang = localStorage.getItem('preferredLanguage');

  if (!lang) {
    // Usar el idioma del navegador si está disponible
    const browserLang = navigator.language.split('-')[0];
    lang = (browserLang === 'es' || browserLang === 'en') ? browserLang : 'es';
  }

  // Establecer el valor del selector
  const selector = document.getElementById('languageSelect');
  if (selector) {
    selector.value = lang;
  }

  // Cambiar el idioma
  changeLanguage(lang);
}

// Función para mapear automáticamente placeholders basados en IDs
function mapPlaceholders(lang) {
  const placeholderMap = {
    'nombre': 'form-nombre-placeholder',
    'email': 'form-email-placeholder',
    'telefono': 'form-telefono-placeholder',
    'asunto': 'form-asunto-placeholder',
    'mensaje': 'form-mensaje-placeholder'
  };

  Object.keys(placeholderMap).forEach(id => {
    const element = document.getElementById(id);
    if (element && translations[lang] && translations[lang][placeholderMap[id]]) {
      element.placeholder = translations[lang][placeholderMap[id]];
    }
  });

  // Mapear labels
  const labelMap = {
    'nombre': 'form-nombre',
    'email': 'form-email',
    'telefono': 'form-telefono',
    'asunto': 'form-asunto',
    'mensaje': 'form-mensaje'
  };

  Object.keys(labelMap).forEach(id => {
    const label = document.querySelector(`label[for="${id}"]`);
    if (label && translations[lang] && translations[lang][labelMap[id]]) {
      label.textContent = translations[lang][labelMap[id]];
    }
  });

  // Actualizar botón del formulario
  const submitBtn = document.querySelector('button[type="submit"]');
  if (submitBtn && translations[lang] && translations[lang]['form-submit']) {
    submitBtn.textContent = translations[lang]['form-submit'];
  }
}

// Función mejorada para cambiar idioma
const originalChangeLanguage = changeLanguage;
changeLanguage = function(lang) {
  originalChangeLanguage(lang);
  mapPlaceholders(lang);
};

// Inicializar cuando el DOM esté listo
document.addEventListener('DOMContentLoaded', () => {
  initializeLanguage();

  // Mapear placeholders después de inicializar
  let currentLang = localStorage.getItem('preferredLanguage') || 'es';
  mapPlaceholders(currentLang);
});

// Escuchar cambios en el selector de idioma
document.getElementById('languageSelect')?.addEventListener('change', (e) => {
  changeLanguage(e.target.value);
});
